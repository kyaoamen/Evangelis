const dictionaries: Record<Locale, Record<MessageKey, string>> = { fr, en };

interface I18nCtx {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: MessageKey) => string;
  tr: (text: I18nText | null | undefined, fallback?: Locale) => string;
  fmtDate: (iso: string | null | undefined, withTime?: boolean) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");

  useEffect(() => {
    try {
      const saved = localStorage.getItem("locale");
      // eslint-disable-next-line react-hooks/set-state-in-effect -- restore persisted preference after hydration
      if (saved === "fr" || saved === "en") setLocaleState(saved);
    } catch {}
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem("locale", l);
    } catch {}
  }, []);

  const t = useCallback((key: MessageKey) => dictionaries[locale][key] ?? key, [locale]);
  const tr = useCallback(
    (text: I18nText | null | undefined, fallback: Locale = "fr") =>
      text ? (text[locale] ?? text[fallback] ?? text.fr ?? text.en ?? "") : "",
    [locale],
  );
  const fmtDate = useCallback(
    (iso: string | null | undefined, withTime = true) => {
      if (!iso) return "";
      const d = new Date(iso);
      return new Intl.DateTimeFormat(locale === "fr" ? "fr-FR" : "en-GB", {
        dateStyle: "medium",
        ...(withTime ? { timeStyle: "short" } : {}),
      }).format(d);
    },
    [locale],
  );

  return <Ctx.Provider value={{ locale, setLocale, t, tr, fmtDate }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n outside I18nProvider");
  return ctx;
}
